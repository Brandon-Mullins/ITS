export function getRasialQuestById(id: string): RasialQuestEntry | undefined {
  return RASIAL_QUESTS.find((q) => q.id === id);
}

export function getRasialQuestByPageName(pageName: string): RasialQuestEntry | undefined {
  const key = pageName.toLowerCase().trim();
  return RASIAL_QUESTS.find(
    (q) =>
      q.pageName.toLowerCase() === key ||
      q.name.toLowerCase() === key ||
      key.includes(q.id.replace(/-/g, ' ')),
  );
}
